    'max_retry_attempts' => (int) env('BLOG_PIPELINE_MAX_RETRY_ATTEMPTS', 2),

    // Pause the run (instead of continuing) when the quality-gate judge fails.
    'pause_on_judge_failure' => (bool) env('BLOG_PIPELINE_PAUSE_ON_JUDGE_FAILURE', false),

