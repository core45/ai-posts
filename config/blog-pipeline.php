        'In today\'s',
        'In the modern world',
        'dive deep',
        'leverage',
        'paradigm',
        'landscape',
        'game-changer',
        'cutting-edge',
        'It\'s worth noting',
        'It is important to remember',
        'A key aspect is',
        // Polish
        'w dzisiejszych czasach',
